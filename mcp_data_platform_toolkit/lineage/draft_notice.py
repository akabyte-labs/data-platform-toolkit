"""
What tells a generated lineage configuration from a checked one, and the
warning that goes with it. No dependency on the MCP library: the draft, the
command line and the tools all use it.

The state is in the file, as data: every generated file says `draft: true`,
and stays a draft (whoever edits it, however its comments change) until the
user removes that line or sets it to false once they checked it. A file
written by hand doesn't say it. While a file in use is a draft, every
lineage answer says so (`DRAFT_IN_USE`).
"""

from __future__ import annotations

# In the header of every generated file (render_yaml): for whoever reads it.
DRAFT_MARKER = "Drafted by draft_lineage_config"
DRAFT_KEY = "draft"

# A wrong configuration is not an error anywhere: nothing else says it.
DRAFT_WARNING = (
    "WARNING: this file was generated automatically and is only a draft. Check it before "
    "relying on it: a wrong layer, a schema ignored by mistake or a missing rule makes the whole "
    "lineage wrong, from the database to the Power BI report, with no error to tell you."
)
HOW_TO_CHECK = "Once checked, remove the line 'draft: true' (or set it to false)."

# In the line of every lineage answer that names the configuration in use.
DRAFT_IN_USE = ("[!] It is a DRAFT, not checked yet ('draft: true'): its layers, ignored schemas "
                "and rules were generated and may be wrong, so this lineage may be too. " + HOW_TO_CHECK)

# The lines render_yaml writes, right after the version.
DRAFT_LINES = (
    "# A draft, generated automatically: check it, then remove this line (or set it to false).",
    "# Until then every lineage answer says the configuration is a draft.",
    f"{DRAFT_KEY}: true",
)


def unfenced(content: str) -> str:
    """The text of the file, without the fence it may have been copied with from the draft."""
    lines = str(content or "").strip().splitlines()
    if lines and lines[0].startswith("```") and lines[-1].strip() == "```":
        lines = lines[1:-1]
    return "\n".join(lines).strip("\n")


def is_generated(text: str) -> bool:
    """True while the file says `draft: true`."""
    try:
        import yaml
        data = yaml.safe_load(unfenced(text))
    except Exception:  # noqa: BLE001 - not YAML: the save reports its problems
        return False
    return isinstance(data, dict) and data.get(DRAFT_KEY) is True

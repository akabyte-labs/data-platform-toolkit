def apply_autodoc_changes(state: dict, mode: str) -> str:
    """Applies the documentation changes to the TMDL file according to the chosen mode."""
    declaration = state["declaration_line"].strip()
    file_name = os.path.basename(state["file_path"])
    plan = plan_autodoc_changes(state, mode)

    if plan["status"] == "empty":
        raise ValueError(
            "'base_description' is empty: pass the business description to write "
            "(see get_description_guidelines). Nothing was written."
        )
    if plan["status"] == "skipped":
        return f"Skipped: documentation already exists for '{declaration}' and mode 'skip' changes nothing."
    if plan["status"] == "unchanged":
        return f"No changes: the proposed documentation is already present for '{declaration}'."

    lines = state["lines"]
    write_start = state["comment_start"] if state["existing_comments"] else state["target_index"]
    new_lines = lines[:write_start] + plan["doc_lines"] + lines[state["target_index"]:]
    write_tmdl_lines(state["file_path"], new_lines, expected_fingerprint=state["fingerprint"])

    message = f"Smart-Doc ({mode}) applied to '{declaration}' in '{file_name}'."
    if plan["removed_legacy"]:
        message += f" Removed {len(plan['removed_legacy'])} auto-generated technical lines."
    if plan["kept_existing"]:
        message += " The existing description was kept: use mode='overwrite' to replace it."
    return message


def write_smart_description(
    project_path: str,
    table_name: str,
    element_name: str,
    base_description: str = "",
    element_type: str = "measure",
    mode: str = "merge",
    is_table: bool = False,
    allow_hidden: bool = False,
    allow_fact_table_columns: bool = False,
    choice: FirstChoice = None,
    user_guidelines: GuidelinesQuestion = None,
) -> str:
    """
    Writes the business description of an element as '///' comments (its
    TMDL description) into the semantic model's file.
    WARNING: modifies project files. Use it after checking the preview with
    'get_smart_description_preview'. Only 'base_description' is written: the
    technical context shown by the preview is never added.
    The first description ever written may come back unwritten, with what to
    do first: the user is asked, once, whether they have rules of their own.

    Args:
        project_path: Root path of the Power BI project / .SemanticModel.
        table_name: Name of the table that contains the element.
        element_name: Name of the element to document.
        base_description: Business description to write (required).
        element_type: Element type (measure | column | dimension | calculationGroup | calculationItem | table).
        mode: overwrite = replace the existing description; merge = keep it,
            drop lines auto-generated by earlier versions, add the new text;
            append = add the new text after the existing one; skip = write
            only if there is no description yet.
        is_table: Compatibility flag (if True, sets element_type='table').
        allow_hidden: If True, also allows documenting hidden elements (isHidden).
        allow_fact_table_columns: If True, also allows documenting the columns
            of fact tables (many side of a one-to-many relationship), which are
            protected by default.
    """
    if is_table:
        element_type = "table"

    if mode not in SUPPORTED_AUTODOC_MODES:
        raise ValueError(f"Invalid mode '{mode}'. Allowed: {', '.join(SUPPORTED_AUTODOC_MODES)}.")
    if not str(base_description or "").strip():
        raise ValueError(
            "'base_description' is empty: pass the business description to write "
            "(see get_description_guidelines). Nothing was written."
        )

    get_table_file_path(project_path, table_name)  # early path validation

    # Once per user, before the first description ever: their own rules.
    notice = ""
    if description_rules.needs_guidelines_question():
        stop, notice = description_rules.settle_guidelines_question(user_guidelines, choice)
        if stop:
            return stop

    # Protected by default, not forbidden: a business Data Dictionary does
    # describe the columns of fact tables, and the protection used to have no
    # way to be lifted (unlike the one on hidden elements).
    if (not allow_fact_table_columns and tmdl.normalize_element_type(element_type) == "column"
            and is_fact_table(project_path, table_name)):
        raise ValueError(
            f"'{table_name}' is on the many side of at least one relationship (fact table): "
            f"its columns are protected. Call the tool again with "
            f"allow_fact_table_columns=True to document them."
        )

    state = gather_autodoc_state(project_path, table_name, element_name, element_type, base_description)

    if not allow_hidden and state["block"].keyword != "table" and tmdl.is_hidden(state["lines"], state["block"]):
        return (
            f"Protected: '{element_name}' is hidden (isHidden), change aborted. "
            f"Call the tool again with allow_hidden=True to force it."
        )

    result = apply_autodoc_changes(state, mode)
    return f"{result}\n{notice}" if notice else result


def set_display_folder(
    project_path: str,
    table_name: str,
    element_name: str,
    element_type: str = "measure",
    display_folder: str = "",
    is_table: bool = False,
) -> str:
    """
    Sets or updates the displayFolder property of a semantic model element.
    Only measures, columns and hierarchies have a display folder: tables and
    calculation items don't, and the call is refused for them.

    Args:
        project_path: Root path of the Power BI project / .SemanticModel.
        table_name: Name of the table that contains the element.
        element_name: Name of the element to modify.
        element_type: Element type (measure | column | dimension | calculationGroup | calculationItem | table).
        display_folder: Display folder to apply (use '\\' for nested levels).
        is_table: Compatibility flag to indicate the element is a table.
    """
    if is_table:
        element_type = "table"
    if not str(display_folder or "").strip():
        raise ValueError("display_folder cannot be empty.")

    return set_element_property_in_file(
        project_path, table_name, element_name, element_type, "displayFolder", display_folder,
        fallback_types=["calculationItem"],
    )


def set_item_visibility(
    project_path: str,
    table_name: str,
    element_name: str,
    element_type: str = "measure",
    is_hidden: bool = True,
    is_table: bool = False,
) -> str:
    """
    Sets the isHidden property to hide or show a semantic model element
    (table, measure, column or hierarchy: calculation items can't be hidden).
    Making an element visible removes the property, as Power BI Desktop does,
    instead of writing 'isHidden: false'.

    Args:
        project_path: Root path of the Power BI project / .SemanticModel.
        table_name: Name of the table that contains the element.
        element_name: Name of the element to modify.
        element_type: Element type (measure | column | dimension | calculationGroup | calculationItem | table).
        is_hidden: True to hide, False to make visible.
        is_table: Compatibility flag to indicate the element is a table.
    """
    if is_table:
        element_type = "table"

    return set_element_property_in_file(
        project_path, table_name, element_name, element_type, "isHidden", is_hidden,
        fallback_types=["calculationItem"],
    )


def format_measure(
    project_path: str,
    table_name: str,
    measure_name: str,
    format_string: str,
    element_type: str = "measure",
    is_table: bool = False,
) -> str:
    """
    Sets or updates the format string of a measure (or column) in TMDL.
    If no measure with that name exists, it is retried as a calculationItem:
    a calculation item has no formatString, so its format is written as the
    DAX expression 'formatStringDefinition = "<format>"'.

    Args:
        project_path: Root path of the Power BI project / .SemanticModel.
        table_name: Name of the table that contains the measure.
        measure_name: Name of the measure to modify.
        format_string: DAX format string (e.g. "#,##0.00%;(#,##0.00%)").
        element_type: Element type (default 'measure'); also accepts 'calculationItem'.
        is_table: Compatibility flag if the element is a table.
    """
    if is_table:
        element_type = "table"
    if not str(format_string or "").strip():
        raise ValueError("format_string cannot be empty.")

    return set_element_property_in_file(
        project_path, table_name, measure_name, element_type, "formatString", format_string,
        fallback_types=["calculationItem"],
    )


def create_measure(
    project_path: str,
    table_name: str,
    measure_name: str,
    dax_expression: str,
    display_folder: str | None = None,
    format_string: str | None = None,
    description: str | None = None,
    is_hidden: bool | None = None,
) -> str:
    """
    Creates a new DAX measure in the TMDL file of the given table.

    Args:
        project_path: Root path of the Power BI project / .SemanticModel.
        table_name: Table in which to create the measure.
        measure_name: Name of the new measure.
        dax_expression: DAX expression (one or more lines).
        display_folder: Optional display folder.
        format_string: Optional format string.
        description: Optional description, written as '///' comments.
        is_hidden: If True, the measure is created hidden.
    """
    return create_tmdl_element(
        project_path, table_name, measure_name, "measure", dax_expression,
        display_folder=display_folder, format_string=format_string,
        description=description, is_hidden=is_hidden,
    )


def create_calculation_item(
    project_path: str,
    table_name: str,
    calculation_item_name: str,
    dax_expression: str,
    display_folder: str | None = None,
    format_string: str | None = None,
    description: str | None = None,
    is_hidden: bool | None = None,
) -> str:
    """
    Creates a new calculationItem in the calculation group of the given table.

    Args:
        project_path: Root path of the Power BI project / .SemanticModel.
        table_name: Table that contains the 'calculationGroup' block.
        calculation_item_name: Name of the new calculation item.
        dax_expression: DAX expression (one or more lines).
        display_folder: Not supported: calculation items have no display
            folder in Power BI, a non-empty value is refused.
        format_string: Optional format string, written as the DAX expression
            'formatStringDefinition = "<format>"' (calculation items have no
            plain formatString).
        description: Optional description, written as '///' comments.
        is_hidden: Not supported: calculation items can't be hidden, True is refused.
    """
    return create_tmdl_element(
        project_path, table_name, calculation_item_name, "calculationItem", dax_expression,
        display_folder=display_folder, format_string=format_string,
        description=description, is_hidden=is_hidden,
    )


def set_ols_permission(
    project_path: str,
    role_name: str,
    table_name: str = "",
    column_name: str = "",
    hidden: bool = True,
    model_permission: str = "",
    create_role_if_missing: bool = True,
) -> str:
    """
    Creates or modifies the Object-Level Security (OLS) of a security role:
    hides or shows a whole table or a single column, writing the
    'metadataPermission' property in the correct 'tablePermission' /
    'columnPermission' block. Unlike the official Microsoft server (more
    focused on RLS), it never touches RLS filters already present on the
    same table.

    Args:
        project_path: Root path of the Power BI project / .SemanticModel.
        role_name: Name of the security role to create or modify.
        table_name: Table to hide/show. Empty to manage only the role itself
            (creation or modelPermission), without touching tables.
        column_name: Column to hide/show (requires table_name). Empty to act
            on the whole table.
        hidden: True hides the object (metadataPermission: none), False makes
            it visible by default (removes the OLS restriction).
        model_permission: Optional model-level permission to set on the role
            (none | read | readRefresh | refresh | restricted | administrator).
            If the role is created now and none is given, 'read' is used.
        create_role_if_missing: If True (default) creates the role when it doesn't exist.
    """
    return ols_roles.set_ols_permission(
        project_path, role_name, table_name, column_name, hidden,
        model_permission or None, create_role_if_missing,
    )


def save_description_guidelines(
    rules: str,
    scope: str = "project",
    project_path: str = "",
    mode: str = "append",
    choice: FirstChoice = None,
) -> str:
    """
    Saves rules for the descriptions that the USER asked for ("in the
    descriptions call the revenue 'turnover'"), added to the built-in ones
    and read by get_description_guidelines. Write the rules as short plain
    sentences, one per line.

    Args:
        rules: The rules to save, as the user wants them applied.
        scope: 'project' (the default): the user's rules for this project
            only, kept in the user's own folder, outside the repository.
            'general': the user's rules for every project. 'repo': the
            rules of the repository, shared with the team through Git: ONLY
            when the user explicitly asks to share them with the team.
        project_path: The .pbip file or folder of the project (not needed
            for 'general').
        mode: 'append' (the default) adds the rules at the end of the file;
            'overwrite' makes them the whole file: read the current rules
            with get_description_guidelines first, and keep the ones the
            user didn't ask to remove.
    """
    notice = settle_first_choice(choice)
    path, created = description_rules.save_rules(rules, scope, project_path, mode)
    sources = description_rules.rule_sources(project_path if scope != "general" else "")
    return (f"{'Created' if created else 'Updated'} '{path}' ({scope} rules).\n"
            + (f"{notice}\n" if notice else "")
            + description_rules.rules_line(sources))


def set_user_folder(location: str) -> str:
    """
    Moves the user's own files (rules for the descriptions, lineage
    configurations) to one of the two standard folders, ONLY when the user
    asks: 'settings' (the settings folder, %APPDATA%\\data-platform-toolkit
    on Windows) or 'documents' (Documents\\data-platform-toolkit, easier to
    open). Files already in the new folder are kept, nothing is overwritten.

    Any other folder can't be chosen from here: tell the user to run, in a
    terminal, mcp-data-platform-toolkit --user-folder "<the folder>".

    Args:
        location: 'settings' or 'documents'.
    """
    target = user_folder.location_folder(str(location or "").strip().lower())
    return "\n".join(user_folder.move_folder(target))


def register_writer_tools(mcp):
    """Registers the write tools on the MCP server."""
    register_tools(mcp, {
        "write_smart_description": write_smart_description,
        "set_display_folder": set_display_folder,
        "set_item_visibility": set_item_visibility,
        "format_measure": format_measure,
        "create_measure": create_measure,
        "create_calculation_item": create_calculation_item,
        "set_ols_permission": set_ols_permission,
        "save_description_guidelines": save_description_guidelines,
        "set_user_folder": set_user_folder,
    }, descriptions={
        "write_smart_description": with_short_guidelines(write_smart_description.__doc__),
    })

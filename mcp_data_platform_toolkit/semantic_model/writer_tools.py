"""
Write tools for the Power BI semantic model (TMDL).

Design notes:
  - properties are written as `name: value` (TMDL syntax), never as
    `name = "value"`, which produces invalid files;
  - booleans use the `isHidden: true|false` form;
  - new elements are inserted inside the table block with the correct
    indentation, not appended to the end of the file;
  - the `calculationItem` fallback does not swallow unrelated exceptions.
"""


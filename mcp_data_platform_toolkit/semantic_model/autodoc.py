"""
Automatic documentation: the '///' description of an element, previewed
with its technical context and written according to a mode.
"""

from __future__ import annotations

import os

from mcp_data_platform_toolkit.semantic_model import tmdl_parser as tmdl
from mcp_data_platform_toolkit.semantic_model.dax_lineage import build_dax_lineage
from mcp_data_platform_toolkit.semantic_model.model_loader import locate_element
from mcp_data_platform_toolkit.semantic_model.tmdl_parser import TmdlError


# The '///' lines ARE the element's `description` property: the text business
# users read in the Data Dictionary. Only the description written by the
# caller goes there. The technical analysis used to be appended to it
# ('/// Depends on physical columns: Sales[Amount].'): exactly the notation
# the description guidelines forbid, and stale as soon as the DAX changed.
# It is now shown by the preview as context for writing the description, and
# never written.

# Lines that earlier versions generated by themselves: mode 'merge' removes
# them, so a model documented with the old behavior can be cleaned up.
_LEGACY_AUTODOC_PREFIXES = (
    "defined in table ", "depends on measures:", "interacts with calculation items:",
    "depends on physical columns:",
)
_LEGACY_AUTODOC_LINES = {
    "data model column.",
    "calculation group with aggregation/filter logic defined in the model.",
    "semantic model table.",
    "automatically documented element.",
}


def is_legacy_autodoc_text(text: str) -> bool:
    """True for a '///' text that an earlier version generated automatically."""
    lowered = (text or "").strip().lower()
    return lowered in _LEGACY_AUTODOC_LINES or lowered.startswith(_LEGACY_AUTODOC_PREFIXES)


def resolve_autodoc_analysis(project_path: str, table_name: str, element_name: str, element_type: str) -> list[str]:
    """
    Technical context of an element (host table, DAX dependencies), to help
    whoever writes its description. Shown by the preview, NEVER written.
    """
    keyword = tmdl.normalize_element_type(element_type)
    if keyword not in ("measure", "calculationItem"):
        return []

    analysis = [f"Defined in table {table_name}."]
    try:
        report = build_dax_lineage(project_path, element_name)
    except (OSError, TmdlError):
        report = {"elements": [], "warnings": []}
    for element in report["elements"]:
        if element["name"].strip().lower() != element_name.strip().lower():
            continue
        if element.get("selected_measure"):
            analysis.append("Applies to the measure in context (SELECTEDMEASURE).")
        if element["measures"]:
            analysis.append("Depends on measures: " + ", ".join(element["measures"]) + ".")
        if element["calc_items"]:
            analysis.append("Interacts with calculation items: " + ", ".join(element["calc_items"]) + ".")
        if element["columns"]:
            analysis.append("Depends on physical columns: " + ", ".join(element["columns"]) + ".")
        if element.get("unresolved"):
            analysis.append("Unresolved references: " + ", ".join(element["unresolved"]) + ".")
    return analysis


def build_autodoc_lines(base_description: str, indent: str) -> list[str]:
    """
    '///' lines of the description: only the caller's text, one line per
    line. Control characters other than line breaks are rejected: they used
    to be written into the file as they were.
    """
    return tmdl.build_doc_lines([base_description], indent)


def normalize_comment_lines(comment_lines: list[str]) -> list[str]:
    return [line.strip()[3:].strip() for line in comment_lines if line.strip().startswith("///")]


def gather_autodoc_state(
    project_path: str,
    table_name: str,
    element_name: str,
    element_type: str,
    base_description: str,
) -> dict:
    # The fingerprint is captured BEFORE reading (see `locate_element`):
    # `gather_autodoc_state` freezes lines and block indices, and the write
    # happens much later (often in a later tool call). Applying old indices to
    # a file rewritten in the meantime doesn't raise an error: it yields a
    # plausibly corrupted file.
    file_path, fingerprint, lines, block = locate_element(
        project_path, table_name, element_name, [element_type])

    existing_comments = tmdl.get_doc_comments(lines, block)
    existing_comments = [line + "\n" for line in existing_comments]
    proposed_lines = build_autodoc_lines(base_description, block.indent)

    return {
        "file_path": file_path,
        "fingerprint": fingerprint,
        "lines": lines,
        "block": block,
        "target_index": block.start,
        "comment_start": block.doc_start,
        "declaration_line": lines[block.start],
        "existing_comments": existing_comments,
        "indent": block.indent,
        "analysis_lines": resolve_autodoc_analysis(project_path, table_name, element_name, element_type),
        "proposed_lines": proposed_lines,
        "existing_texts": normalize_comment_lines(existing_comments),
        "proposed_texts": normalize_comment_lines([line.rstrip() for line in proposed_lines]),
    }


def plan_autodoc_changes(state: dict, mode: str) -> dict:
    """
    The '///' block the element will have after writing with `mode`.

    {"doc_lines": new lines, or None when nothing changes,
     "status": "changed" | "unchanged" | "skipped" | "empty",
     "removed_legacy": [texts removed by 'merge'],
     "kept_existing": True when an existing description stays next to the new text}

    Modes:
      overwrite  the new description replaces the existing one;
      merge      earlier auto-generated lines are removed, the other existing
                 lines are kept, the new lines not already present are added;
      append     the new lines not already present are added, nothing removed;
      skip       nothing is written if a description already exists.
    'merge' used to behave exactly like 'append': a changed description was
    appended under the old one, and the two accumulated at every run.
    """
    existing = state["existing_comments"]
    existing_texts = state["existing_texts"]
    proposed = state["proposed_lines"]
    plan = {"doc_lines": None, "status": "unchanged", "removed_legacy": [], "kept_existing": False}

    if not proposed:
        plan["status"] = "empty"
        return plan
    if mode == "skip" and existing:
        plan["status"] = "skipped"
        return plan

    if mode == "overwrite":
        new_doc = list(proposed)
    else:
        kept = list(existing)
        if mode == "merge":
            kept = [line for line, text in zip(existing, existing_texts, strict=True)
                    if not is_legacy_autodoc_text(text)]
            plan["removed_legacy"] = [text for text in existing_texts if is_legacy_autodoc_text(text)]
        seen = set(normalize_comment_lines(kept))
        additions = []
        for text, line in zip(state["proposed_texts"], proposed, strict=True):
            if text not in seen:
                additions.append(line)
                seen.add(text)
        plan["kept_existing"] = bool(kept) and bool(additions)
        new_doc = kept + additions

    if [line.rstrip() for line in new_doc] != [line.rstrip() for line in existing]:
        plan["doc_lines"] = new_doc
        plan["status"] = "changed"
    return plan


def prepare_autodoc_preview(
    project_path: str,
    table_name: str,
    element_name: str,
    element_type: str,
    base_description: str,
    mode: str,
    state: dict | None = None,
) -> str:
    if state is None:
        state = gather_autodoc_state(project_path, table_name, element_name, element_type, base_description)
    plan = plan_autodoc_changes(state, mode)

    preview = [
        "=== AUTODOC PREVIEW ===",
        f"File: {os.path.basename(state['file_path'])}",
        f"Element: {element_type} '{element_name}' in '{table_name}'",
        f"Mode: {mode}",
        "",
        "Existing description:",
    ]
    preview.extend([line.rstrip() for line in state["existing_comments"]] or ["(none)"])
    preview.append("")
    preview.append("Proposed description:")
    preview.extend(line.rstrip() for line in state["proposed_lines"])
    if not state["proposed_lines"]:
        preview.append("(none: pass the business description in 'base_description')")

    if plan["status"] == "changed":
        preview.append("")
        preview.append(f"Description after writing ({mode}):")
        preview.extend(line.rstrip() for line in plan["doc_lines"])

    if state["analysis_lines"]:
        preview.append("")
        preview.append("Technical context (NOT written: use it only to understand the element):")
        preview.extend(f"  {line}" for line in state["analysis_lines"])

    preview.append("")
    preview.append("Say only what the existing description, the technical context, the rules "
                   "(get_description_guidelines) or the user support: ask about the agreements, "
                   "thresholds, causes or company terms you cannot see, and keep the facts of the "
                   "existing description.")
    if mode == "overwrite" and state["existing_comments"] and state["proposed_lines"]:
        preview.append("Overwrite replaces the existing description: the new text must still hold "
                       "everything the old one says, unless the DAX contradicts it.")

    status = {
        "changed": "changes available.",
        "unchanged": "no changes needed.",
        "skipped": "a description already exists and mode 'skip' changes nothing.",
        "empty": "nothing to write until 'base_description' is given.",
    }[plan["status"]]
    preview.append("")
    preview.append(f"Status: {status}")
    if plan["removed_legacy"]:
        preview.append(f"Note: {len(plan['removed_legacy'])} auto-generated technical lines of an "
                       f"earlier version will be removed.")
    if plan["kept_existing"]:
        preview.append("Note: the existing description is kept and the new text is added after "
                       "it. Use mode='overwrite' to replace it.")
    return "\n".join(preview)
